  await page.getByRole('button',{name:'Details & Booking',exact:true}).first().click();
  await page.getByPlaceholder('Ali / John').fill('Browser Guest');
  assert.equal(await page.locator('input[type=date]').nth(0).inputValue(),checkIn);
  await page.getByPlaceholder('+374 91 ...').fill('+37491123456');await page.locator('input[type=checkbox]').last().check();
